#!/usr/bin/env node
// Writes src/python.js from the web app's Pyodide worker, so the command line runs the worker's
// Python text unchanged. With --check it fails instead of writing when src/python.js differs.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const workerUrl = new URL('../../../apps/dicompare/src/workers/pyodide.worker.ts', import.meta.url);
const outputPath = fileURLToPath(new URL('../src/python.js', import.meta.url));

// Each call: where it starts in the worker, the opening text of its template, and the only
// interpolations it may contain (the generated function takes them as parameters).
const CALLS = [
  { name: 'installCode', after: 'if (inElectronProd) {', open: 'installCode = `', method: 'runPythonAsync', parameters: ['wheelBase', 'bundledWheels'] },
  { name: 'versionCode', after: 'async function initializePyodide(', open: 'pyodide.runPython(`', method: 'runPython', parameters: ['DICOMPARE_VERSION'] },
  { name: 'analyzeFilesCode', after: 'async function handleAnalyzeFiles(', open: 'pyodide.runPythonAsync(`', method: 'runPythonAsync', parameters: [] },
  { name: 'validateAcquisitionCode', after: 'async function handleValidateAcquisition(', open: 'pyodide.runPython(`', method: 'runPython', parameters: [] },
];

function template(source, { name, after, open, parameters }) {
  const from = source.indexOf(after);
  if (from < 0) throw new Error(`${name}: the worker no longer contains "${after}"`);
  const start = source.indexOf(open, from);
  if (start < 0) throw new Error(`${name}: no "${open}" after "${after}"`);
  const bodyStart = start + open.length;
  const end = source.indexOf('`', bodyStart);
  const body = source.slice(bodyStart, end);
  const interpolations = [...body.matchAll(/\$\{([^}]*)\}/g)].map((match) => match[1]);
  const allowed = new Set(parameters.flatMap((parameter) => [parameter, `JSON.stringify(${parameter})`]));
  const unexpected = interpolations.filter((expression) => !allowed.has(expression));
  if (unexpected.length) throw new Error(`${name}: unexpected interpolations ${unexpected.join(', ')}`);
  return body;
}

export async function pythonCalls() {
  // A Windows checkout may convert the worker to CRLF; the generated module is always LF.
  const source = (await readFile(workerUrl, 'utf8')).replace(/\r\n/g, '\n');
  const lines = [
    '// Generated by scripts/sync-python-calls.mjs from apps/dicompare/src/workers/pyodide.worker.ts.',
    '// Do not edit: rerun the script after an upstream sync changes the worker.',
  ];
  for (const call of CALLS) {
    const body = template(source, call);
    const value = call.parameters.length ? `(${call.parameters.join(', ')}) => \`${body}\`` : `\`${body}\``;
    lines.push('', `export const ${call.name} = ${value};`, `export const ${call.name.replace(/Code$/, 'Method')} = '${call.method}';`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await pythonCalls();
  if (process.argv.includes('--check')) {
    if (text !== (await readFile(outputPath, 'utf8')).replace(/\r\n/g, '\n')) {
      console.error('src/python.js differs from the web worker: run node packages/dicompare/scripts/sync-python-calls.mjs');
      process.exitCode = 1;
    }
  } else {
    await writeFile(outputPath, text);
  }
}
