function build_container(source, spm, output)
% Called by build_container.py after verifying the pinned, repaired sources.
assert(strcmp(version('-release'), '2023b'), 'The reference requires MATLAB R2023b');
assert(strcmp(computer, 'GLNXA64'), 'Build the Linux x86-64 reference on Linux');
assert(license('test', 'Compiler'), 'A MATLAB Compiler license is required to build the Runtime application');
addpath(genpath(source));
addpath(spm);
previous = pwd;
restore = onCleanup(@() cd(previous));
cd(output);
% Include dynamically selected pRF functions and GIfTI readers in the archive.
result = compiler.build.standaloneApplication( ...
    fullfile(source, 'Utils', 'SamSrfAnalysis.m'), ...
    'ExecutableName', 'SamSrfReference', ...
    'AdditionalFiles', {source, spm}, ...
    'OutputDir', fullfile(output, 'application'), ...
    'Verbose', 'on');
runtime = compiler.runtime.createDockerImage(result, ...
    'ImageName', 'samsrf-reference-runtime:r2023b', ...
    'DockerContext', fullfile(output, 'runtime'));
compiler.package.docker(result, ...
    'RuntimeImage', runtime, ...
    'ImageName', 'samsrf-reference:41ed1e96-r2023b', ...
    'DockerContext', fullfile(output, 'container'));
copyfile(fullfile(source, 'SamSrf_defaults.json'), fullfile(output, 'SamSrf_defaults.json'));
environment = struct('matlab', version, 'release', version('-release'), ...
    'computer', computer, 'blas', version('-blas'), 'toolboxes', ver);
file = fopen(fullfile(output, 'build-environment.json'), 'w');
assert(file >= 0, 'Cannot write the build environment');
closeFile = onCleanup(@() fclose(file));
fprintf(file, '%s\n', jsonencode(environment, 'PrettyPrint', true));
end
