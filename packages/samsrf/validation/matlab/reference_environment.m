function environment = reference_environment(mode)
% Capture requests separately from MATLAB's observations. An environment
% variable alone is never evidence of an effective CNR branch.
assert(startsWith(version, '23.2.0.3097123'), 'Reference requires R2023b Update 11');
maxNumCompThreads(1);
threads = maxNumCompThreads;
assert(threads == 1, 'MATLAB did not honor the computational thread limit');
[status, cpu] = system('lscpu');
assert(status == 0, 'Cannot record CPU provenance');
requested = struct('mklCbwr',getenv('MKL_CBWR'), ...
    'mklNumThreads',getenv('MKL_NUM_THREADS'), ...
    'ompNumThreads',getenv('OMP_NUM_THREADS'), ...
    'mklDynamic',getenv('MKL_DYNAMIC'),'ompDynamic',getenv('OMP_DYNAMIC'));
assert(strcmp(requested.mklCbwr,'COMPATIBLE'), 'Request MKL_CBWR=COMPATIBLE');
assert(strcmp(requested.mklNumThreads,'1') && strcmp(requested.ompNumThreads,'1'), ...
    'Request one BLAS/OpenMP thread before starting MATLAB');
assert(strcmp(requested.mklDynamic,'FALSE') && strcmp(requested.ompDynamic,'FALSE'), ...
    'Disable dynamic threading before starting MATLAB');
blas = version('-blas');
environment = struct('matlab',version,'release',version('-release'), ...
    'computer',computer,'toolboxes',ver,'cpu',cpu,'executionMode',mode, ...
    'requested',requested,'observed',struct('blas',blas, ...
    'maxComputationalThreads',threads), ...
    'crossHostReproducibilityVerified',false, ...
    'unverifiedControls',{{'Effective MKL CNR branch','Effective MKL dynamic threading'}}, ...
    'githubRun',getenv('GITHUB_RUN_ID'),'githubAttempt',getenv('GITHUB_RUN_ATTEMPT'));
end
