#!/usr/bin/env python3
"""Generate the deconvolution WebAssembly module's third-party notices from the locked Cargo graph.

    python scripts/deconvolution-third-party-notices.py          write the notices
    python scripts/deconvolution-third-party-notices.py --check  fail when they are out of date

The closure is the crates `deconvolution-wasm` links into wasm32 (normal edges, proc-macros
excluded: they run at build time and ship no code). Each crate's licence text is copied verbatim
from its published crate, copyright lines included. Modelled on greedy-third-party-notices.py.
"""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT / 'exes/deconvolution'
OUTPUT = ROOT / 'packages/deconvolution/THIRD_PARTY_NOTICES.md'
TARGET = 'wasm32-unknown-unknown'
MARKERS = {
    'MIT': (('LICENSE-MIT', 'LICENSE-MIT.md', 'LICENSE.md', 'LICENSE', 'LICENSE.txt'), ('Permission is hereby granted, free of charge',)),
    'Apache-2.0': (('LICENSE-APACHE', 'LICENSE-APACHE.md', 'LICENSE.md', 'LICENSE', 'LICENSE.txt'), ('Apache License', 'Version 2.0, January 2004')),
    'Unicode-3.0': (('LICENSE-UNICODE',), ('UNICODE LICENSE V3',)),
}


def run(*args):
    return subprocess.run(args, cwd=WORKSPACE, check=True, capture_output=True, text=True).stdout


def package_closure():
    metadata = json.loads(run('cargo', 'metadata', '--locked', '--format-version', '1'))
    by_name_version = {}
    for package in metadata['packages']:
        by_name_version.setdefault((package['name'], package['version']), []).append(package)
    tree = run('cargo', 'tree', '--locked', '--color', 'never', '-p', 'deconvolution-wasm', '--target', TARGET,
               '--edges', 'normal,no-proc-macro', '--prefix', 'none', '--format', '{p}')
    closure = set()
    for line in tree.splitlines():
        match = re.match(r'^(\S+) v(\S+)(?: \(.+\))?$', line)
        if not match:
            raise ValueError(f'Cannot parse cargo tree package line: {line!r}')
        closure.add(match.groups())
    packages = []
    for key in sorted(closure):
        matches = by_name_version.get(key, [])
        if len(matches) != 1:
            raise ValueError(f'Expected one metadata package for {key}, found {len(matches)}')
        # Workspace crates (no source) are this repository's own MIT code.
        if matches[0]['source'] is not None:
            packages.append(matches[0])
    return packages


def license_text(package, license_name):
    preferred, markers = MARKERS[license_name]
    directory = Path(package['manifest_path']).parent
    files = [path for path in directory.iterdir() if path.is_file() and re.match(r'^(licen[cs]e|copying)', path.name, re.IGNORECASE)]
    order = {name: index for index, name in enumerate(preferred)}
    files.sort(key=lambda path: (order.get(path.name, len(order)), path.name))
    for path in files:
        text = path.read_text(encoding='utf8').strip()
        if all(marker in text for marker in markers):
            return path.name, text
    raise FileNotFoundError(f"{package['name']} {package['version']} permits {license_name}, but its crate has no matching licence text")


def selected_licenses(package):
    """One licence from each AND term: MIT where offered, else Apache-2.0, else the term itself."""
    expression = package.get('license') or ''
    terms = [term.strip().strip('()') for term in re.split(r'\s+AND\s+', expression)]
    selected = []
    for term in terms:
        alternatives = [item.strip() for item in term.split(' OR ')]
        choice = next((name for name in ('MIT', 'Apache-2.0', 'Unicode-3.0') if name in alternatives), None)
        if choice is None:
            raise ValueError(f"{package['name']} {package['version']} has licence {expression!r}; review it before distribution")
        selected.append(choice)
    return selected


def render():
    sections = [
        '# Deconvolution WebAssembly third-party notices',
        '',
        'Generated by `python scripts/deconvolution-third-party-notices.py` from the locked',
        'dependency closure that `exes/deconvolution/wasm` links into',
        '`wasm/deconvolution_wasm_bg.wasm` (wasm32, proc-macros excluded). Do not edit this file',
        'by hand. The Sun Microsystems notice of the Bessel functions libm ports is in NOTICE.',
    ]
    for package in package_closure():
        sections.extend(['', f"## {package['name']} {package['version']}", '', f"Declared licence: `{package['license']}`"])
        if package.get('repository'):
            sections.extend(['', f"Repository: {package['repository']}"])
        if package.get('authors'):
            sections.extend(['', 'Authors: ' + '; '.join(package['authors'])])
        for license_name in selected_licenses(package):
            filename, text = license_text(package, license_name)
            sections.extend(['', f'Selected licence: `{license_name}` from `{filename}`', '', '```text', text, '```'])
    return '\n'.join(sections) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf8') != content:
            print(f'Out of date: {OUTPUT.relative_to(ROOT)}; run python scripts/deconvolution-third-party-notices.py', file=sys.stderr)
            return 1
        print(f'Verified {OUTPUT.relative_to(ROOT)}')
        return 0
    OUTPUT.write_text(content, encoding='utf8')
    print(OUTPUT.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
