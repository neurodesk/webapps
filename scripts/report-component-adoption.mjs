#!/usr/bin/env node
// Generates docs/architecture/component-adoption.md: which shared
// @neurodesk/webapp-components subpaths each app actually imports, plus the
// current fork ratchet. Run after changing app imports so stalled migrations
// and dead exports stay visible: `node scripts/report-component-adoption.mjs`.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { loadAppsRegistry, repoRoot } from './lib/apps-registry.mjs';

const SKIP_DIRECTORIES = new Set([
  '.git', '.tmp_model_env', '.turbo', 'coverage', 'dist', 'dist-sites', 'fixtures',
  'legacy-ci', 'node_modules', 'test-results', 'vendor',
]);
const SOURCE_EXTENSIONS = new Set(['.js', '.mjs', '.ts', '.tsx', '.html']);
const IMPORT_PATTERN = /@neurodesk\/webapp-components(\/[\w./-]*)?/g;

async function collectFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRECTORIES.has(entry.name)) continue;
      files.push(...await collectFiles(join(directory, entry.name)));
    } else if (SOURCE_EXTENSIONS.has(entry.name.slice(entry.name.lastIndexOf('.')))) {
      files.push(join(directory, entry.name));
    }
  }
  return files;
}

function subpathOf(specifier) {
  const suffix = specifier.replace('@neurodesk/webapp-components', '');
  if (!suffix || suffix === '/') return '(root)';
  return suffix.replace(/^\//, '').replace(/\.js$/, '');
}

const registry = await loadAppsRegistry();
const rows = [];
const allSubpaths = new Set();

for (const app of registry.apps) {
  const used = new Map();
  for (const path of await collectFiles(join(repoRoot, 'apps', app.id))) {
    let source = await readFile(path, 'utf8');
    // Import-map declarations alias the package; only count real usage.
    if (path.endsWith('.html')) {
      source = source.replace(/<script type="importmap">[\s\S]*?<\/script>/gi, '');
    }
    for (const match of source.matchAll(IMPORT_PATTERN)) {
      const subpath = subpathOf(match[0]);
      allSubpaths.add(subpath);
      if (!used.has(subpath)) used.set(subpath, new Set());
      used.get(subpath).add(relative(join(repoRoot, 'apps', app.id), path));
    }
  }
  rows.push({ app, used });
}

const subpaths = [...allSubpaths].sort();
const lines = [
  '# Shared component adoption',
  '',
  '<!-- Generated by scripts/report-component-adoption.mjs — do not edit by hand. -->',
  '',
  'Real `@neurodesk/webapp-components` imports per app (import-map aliases excluded).',
  'Apps absent from a column ship their own code for that concern or do not need it;',
  'the fork ratchet in `test/component-forks.test.mjs` lists which of those are forks.',
  '',
  `| App | ${subpaths.join(' | ')} |`,
  `| --- | ${subpaths.map(() => '---').join(' | ')} |`,
];
for (const { app, used } of rows) {
  lines.push(`| ${app.id} | ${subpaths.map((subpath) => (used.has(subpath) ? '✓' : '')).join(' | ')} |`);
}

lines.push('', '## Import sites', '');
for (const { app, used } of rows) {
  if (!used.size) continue;
  lines.push(`- **${app.id}**`);
  for (const [subpath, files] of [...used.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  - \`${subpath}\`: ${[...files].sort().join(', ')}`);
  }
}
lines.push('');

const target = join(repoRoot, 'docs', 'architecture', 'component-adoption.md');
await writeFile(target, lines.join('\n'));
console.log(`Wrote ${relative(repoRoot, target)}`);
