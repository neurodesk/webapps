#!/usr/bin/env node
// Merge an app's upstream repository into its monorepo copy.
//   node scripts/sync-upstream.mjs --app dicompare [--target <commit>] [--body <file>]
// Moves the app's `source:` pin in registry/apps.yml, writes a changeset and,
// with --body, a pull request description. Prints a JSON summary.
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { loadAppsRegistry, registryPath, repoRoot } from './lib/apps-registry.mjs';
import { EMBEDDED_VERSION_SITES } from './lib/app-versions.mjs';
import { PACKAGE_VERSION_SITE, mergeUpstream } from './lib/upstream-sync.mjs';

const option = name => {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
};
const id = option('--app');
const app = (await loadAppsRegistry()).apps.find(item => item.id === id);
if (!app) throw new Error(`Unknown app: ${id}`);
const appDir = join(repoRoot, 'apps', id);
const config = JSON.parse(await readFile(join(appDir, 'upstream.json'), 'utf8'));
const [repository, base] = app.source.split('@');
if (!process.env.TMPDIR) throw new Error('Set TMPDIR for the upstream clone.');
const upstream = join(process.env.TMPDIR, 'upstream', repository);
const git = (...args) => execFileSync('git', ['-C', upstream, ...args], { encoding: 'utf8' }).trim();

if (existsSync(upstream)) git('fetch', '--quiet', 'origin');
else execFileSync('git', ['clone', '--quiet', '--filter=blob:none', `https://github.com/${repository}.git`, upstream]);
const target = git('rev-parse', option('--target') || `origin/${config.branch || 'main'}`);
const commits = target === base ? [] : git('log', '--reverse', '--format=%H%x09%s', `${base}..${target}`).split('\n').filter(Boolean).map(line => line.split('\t'));
if (!commits.length) {
  console.log(JSON.stringify({ app: id, base, target, commits: 0 }));
  process.exit(0);
}

const prefix = `apps/${id}/`;
const versionSites = [PACKAGE_VERSION_SITE, ...(EMBEDDED_VERSION_SITES[id] || [])
  .filter(site => site.file.startsWith(prefix))
  .map(site => ({ ...site, file: site.file.slice(prefix.length) }))];
const name = JSON.parse(await readFile(join(appDir, 'package.json'), 'utf8')).name;
const report = mergeUpstream({ upstream, base, target, appDir, config, versionSites });

const registry = await readFile(registryPath, 'utf8');
const pin = `source: ${app.source}`;
if (registry.split(pin).length !== 2) throw new Error(`Cannot find a unique '${pin}' in registry/apps.yml`);
await writeFile(registryPath, registry.replace(pin, `source: ${repository}@${target}`));
const short = `${base.slice(0, 7)}..${target.slice(0, 7)}`;
await writeFile(join(repoRoot, '.changeset', `upstream-${id}.md`), [
  '---', `"${name}": patch`, '---', '',
  `Merge upstream ${repository} ${short}:`, '',
  ...commits.map(([, subject]) => `- ${subject}`), '',
].join('\n'));

const byStatus = status => report.filter(item => item.status === status);
const conflicts = byStatus('conflict');
const section = (title, items) => items.length
  ? [`### ${title} (${items.length})`, '', ...items.map(item => `- \`${item.path}\`${item.reason ? `: ${item.reason}` : ''}`), '']
  : [];
const body = [
  `Merges [${repository}](https://github.com/${repository}) [\`${short}\`](https://github.com/${repository}/compare/${base}...${target}) into \`apps/${id}\` (${commits.length} commits).`,
  '',
  conflicts.length
    ? `**${conflicts.length} file(s) have conflict markers.** Resolve them on this branch, then mark the PR ready.`
    : 'Every change merged cleanly. Review the diff and CI before merging.',
  '',
  ...section('Conflicts', conflicts),
  ...section('Kept the monorepo copy', byStatus('kept')),
  ...section('Merged', byStatus('merged')),
  ...section('Added', [...byStatus('added'), ...byStatus('updated')]),
  ...section('Deleted', byStatus('deleted')),
  ...section('Not imported: replaced by shared monorepo code', byStatus('dropped')),
  ...section('Not imported: ignored by upstream.json', byStatus('ignored')),
  ...(config.integration?.length ? ['### Keep when resolving', '', ...config.integration.map(rule => `- ${rule}`), ''] : []),
  '### Upstream commits', '',
  ...commits.map(([sha, subject]) => `- ${repository}@${sha} ${subject}`),
  '',
  `Generated by \`node scripts/sync-upstream.mjs --app ${id}\`; rules live in \`apps/${id}/upstream.json\`.`,
].join('\n');
if (option('--body')) await writeFile(option('--body'), `${body}\n`);
console.log(JSON.stringify({ app: id, base, target, commits: commits.length, conflicts: conflicts.map(item => item.path) }));
