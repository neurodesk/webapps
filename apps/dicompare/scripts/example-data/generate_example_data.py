#!/usr/bin/env python3
"""Generate the synthetic example session bundled with dicompare-web.

The session is published to the pinned dataset and
loaded by the shared example selector, so people without DICOMs of their own can
try dicompare in one click. Every file is synthetic: the pixel data is a small
numerical phantom and the headers carry no subject information.

It holds two acquisitions from a fictional 3T Siemens session:

* T1w_MPR - a 3D MPRAGE whose parameters match the HCP Young Adult
  "T1-weighted 3D MPRAGE" reference, so it validates cleanly against that
  library schema.
* QSM_ME_GRE - a five-echo 3D GRE (magnitude and phase) for QSM, validated
  against the "QSM Consensus Guidelines" schema. It is deliberately imperfect:
    - echo times 6.0, 13.5, 21.0, 27.0, 34.5 ms give spacings of
      7.5, 7.5, 6.0, 7.5 ms (fails "Uniform Echo Spacing");
    - PixelBandwidth 300 Hz/pixel at 3T (fails "Readout Bandwidth", max 220);
    - first echo 6.0 ms (warns on "Short First Echo": <= 10 ms required,
      <= 5 ms preferred).
  Every other QSM check passes.

Only a few slices of each volume are written so the bundle stays small; the
slice count does not affect any check.

Usage (needs pydicom and numpy):
    python3 scripts/example-data/generate_example_data.py

The output is deterministic, so re-running it reproduces the published zip.
"""

from __future__ import annotations

import io
import os
import zipfile
from pathlib import Path

import numpy as np
import pydicom
from pydicom.dataset import Dataset, FileMetaDataset
from pydicom.uid import ExplicitVRLittleEndian, MRImageStorage, generate_uid

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_ZIP = Path(os.environ["TMPDIR"]) / "dicompare-example-session.zip"
SESSION_DIR = "dicompare-example-session"

# Fixed (fictional) study date/time so the output is reproducible.
STUDY_DATE = "20260101"
STUDY_TIME = "090000.000000"
ZIP_TIMESTAMP = (2026, 1, 1, 0, 0, 0)

README = """dicompare example session
=========================

Synthetic, anonymized DICOMs for trying dicompare (https://github.com/astewartau/dicompare-web).
No real subject data: the images are a small numerical phantom and only a few
slices of each volume are included. Generated by
scripts/example-data/generate_example_data.py.

T1w_MPR/      3D T1-weighted MPRAGE (3T Siemens). Matches the HCP Young Adult
              "T1-weighted 3D MPRAGE" library schema.
QSM_ME_GRE/   Five-echo 3D GRE for QSM, magnitude and phase. Against the
              "QSM Consensus Guidelines" library schema it fails Uniform Echo
              Spacing (spacings 7.5, 7.5, 6.0, 7.5 ms) and Readout Bandwidth
              (300 Hz/pixel at 3T, max 220), warns on Short First Echo
              (6.0 ms; <= 5 ms preferred) and passes every other check.
"""


def uid(*parts: object) -> str:
    """Deterministic UID derived from the given parts."""
    return generate_uid(entropy_srcs=["dicompare-example-session", *map(str, parts)])


def base_dataset() -> Dataset:
    """Patient, study and equipment attributes shared by every file."""
    ds = Dataset()
    ds.SpecificCharacterSet = "ISO_IR 100"
    ds.SOPClassUID = MRImageStorage
    ds.Modality = "MR"

    # Anonymized, synthetic subject.
    ds.PatientName = "Example^Synthetic"
    ds.PatientID = "DICOMPARE-EXAMPLE"
    ds.PatientBirthDate = ""
    ds.PatientSex = "O"
    ds.PatientAge = ""
    ds.PatientIdentityRemoved = "YES"
    ds.DeidentificationMethod = "Synthetic phantom data; no subject information"
    ds.BodyPartExamined = "HEAD"

    ds.StudyInstanceUID = uid("study")
    ds.StudyID = "1"
    ds.StudyDate = STUDY_DATE
    ds.StudyTime = STUDY_TIME
    ds.StudyDescription = "dicompare^example"
    ds.AccessionNumber = ""
    ds.ReferringPhysicianName = ""
    ds.FrameOfReferenceUID = uid("frame-of-reference")
    ds.PositionReferenceIndicator = ""

    ds.Manufacturer = "SIEMENS"
    ds.ManufacturerModelName = "Prisma_fit"
    ds.SoftwareVersions = "syngo MR XA30"
    ds.StationName = "EXAMPLE"
    ds.MagneticFieldStrength = 3
    ds.ImagingFrequency = 123.25
    ds.ImagedNucleus = "1H"
    ds.TransmitCoilName = "Body"
    ds.ReceiveCoilName = "HeadNeck_64"
    ds.PatientPosition = "HFS"
    return ds


def phantom(rows: int, cols: int, nslices: int, slice_index: int) -> np.ndarray:
    """Smooth head-like ellipsoid phantom, normalised to [0, 1]."""
    y, x = np.mgrid[-1:1:rows * 1j, -1:1:cols * 1j]
    z = (slice_index - (nslices - 1) / 2) / max(nslices, 1) * 0.4
    head = (x / 0.75) ** 2 + (y / 0.9) ** 2 + (z / 0.9) ** 2
    img = np.where(head < 1.0, 0.55, 0.0)
    img = np.where(head < 0.8, 0.8, img)  # "brain"
    ventricles = ((np.abs(x) - 0.12) / 0.08) ** 2 + (y / 0.3) ** 2
    img = np.where((head < 0.8) & (ventricles < 1.0), 0.35, img)
    nuclei = ((np.abs(x) - 0.3) / 0.08) ** 2 + ((y + 0.05) / 0.12) ** 2
    img = np.where((head < 0.8) & (nuclei < 1.0), 1.0, img)
    return img


def axial_geometry(ds: Dataset, rows: int, cols: int, spacing: float, slice_index: int) -> None:
    ds.ImageOrientationPatient = [1, 0, 0, 0, 1, 0]
    z = slice_index * spacing
    ds.ImagePositionPatient = [-(cols * spacing) / 2, -(rows * spacing) / 2, z]
    ds.SliceLocation = z


def pixel_attributes(ds: Dataset, pixels: np.ndarray) -> None:
    ds.SamplesPerPixel = 1
    ds.PhotometricInterpretation = "MONOCHROME2"
    ds.Rows, ds.Columns = pixels.shape
    ds.BitsAllocated = 16
    ds.BitsStored = 12
    ds.HighBit = 11
    ds.PixelRepresentation = 0
    ds.PixelData = pixels.astype("<u2").tobytes()


def finish(ds: Dataset) -> bytes:
    meta = FileMetaDataset()
    meta.MediaStorageSOPClassUID = ds.SOPClassUID
    meta.MediaStorageSOPInstanceUID = ds.SOPInstanceUID
    meta.TransferSyntaxUID = ExplicitVRLittleEndian
    meta.ImplementationClassUID = uid("implementation")
    meta.ImplementationVersionName = "DICOMPARE_EX"
    ds.file_meta = meta
    buf = io.BytesIO()
    if int(pydicom.__version__.split(".")[0]) >= 3:
        pydicom.dcmwrite(buf, ds, enforce_file_format=True)
    else:  # pydicom 2.x, as pinned by dicompare
        ds.is_little_endian, ds.is_implicit_VR = True, False
        pydicom.dcmwrite(buf, ds, write_like_original=False)
    return buf.getvalue()


def t1w_mprage() -> dict[str, bytes]:
    """HCP-style 0.7 mm 3D MPRAGE (3 slices of 320 x 320)."""
    rows = cols = 320
    spacing = 0.7
    nslices = 3
    series_uid = uid("t1w", "series")
    files = {}
    for k in range(nslices):
        ds = base_dataset()
        ds.SeriesInstanceUID = series_uid
        ds.SeriesNumber = 2
        ds.SeriesDescription = "T1w_MPR"
        ds.ProtocolName = "T1w_MPR"
        ds.SeriesDate = STUDY_DATE
        ds.SeriesTime = "090500.000000"
        ds.AcquisitionNumber = 1
        ds.InstanceNumber = k + 1
        ds.SOPInstanceUID = uid("t1w", k)
        ds.ImageType = ["ORIGINAL", "PRIMARY", "M", "ND", "NORM"]

        ds.ScanningSequence = ["GR", "IR"]
        ds.SequenceVariant = ["SK", "SP", "MP"]
        ds.ScanOptions = "IR"
        ds.MRAcquisitionType = "3D"
        ds.SequenceName = "*tfl3d1_16ns"
        ds.AngioFlag = "N"
        ds.RepetitionTime = 2400
        ds.EchoTime = 2.14
        ds.InversionTime = 1000
        ds.FlipAngle = 8
        ds.NumberOfAverages = 1
        ds.EchoNumbers = 1
        ds.EchoTrainLength = 1
        ds.PixelBandwidth = 210
        ds.PercentSampling = 100
        ds.PercentPhaseFieldOfView = 100
        ds.AcquisitionMatrix = [0, 320, 320, 0]
        ds.InPlanePhaseEncodingDirection = "COL"
        ds.ParallelReductionFactorInPlane = 2
        ds.SliceThickness = spacing
        ds.SpacingBetweenSlices = spacing
        ds.PixelSpacing = [spacing, spacing]
        ds.SAR = 0.05
        axial_geometry(ds, rows, cols, spacing, k)

        img = phantom(rows, cols, nslices, k)
        t1_contrast = np.where(img > 0.9, 0.7, img)  # deep GM darker than WM
        pixel_attributes(ds, np.round(t1_contrast * 1800))
        ds.WindowCenter = 900
        ds.WindowWidth = 1800
        files[f"T1w_MPR/IM-0002-{k + 1:04d}.dcm"] = finish(ds)
    return files


def qsm_multi_echo_gre() -> dict[str, bytes]:
    """Five-echo 1 mm isotropic 3D GRE, magnitude and phase (4 slices of 96 x 96)."""
    rows = cols = 96
    spacing = 1.0
    nslices = 4
    echo_times = [6.0, 13.5, 21.0, 27.0, 34.5]  # spacings 7.5, 7.5, 6.0, 7.5 ms
    files = {}
    for part, series_number, image_type in (
        ("mag", 3, ["ORIGINAL", "PRIMARY", "M", "ND"]),
        ("phase", 4, ["ORIGINAL", "PRIMARY", "P", "ND"]),
    ):
        series_uid = uid("qsm", part, "series")
        instance = 0
        for e, te in enumerate(echo_times):
            for k in range(nslices):
                instance += 1
                ds = base_dataset()
                ds.SeriesInstanceUID = series_uid
                ds.SeriesNumber = series_number
                ds.SeriesDescription = "QSM_ME_GRE" if part == "mag" else "QSM_ME_GRE_ph"
                ds.ProtocolName = "QSM_ME_GRE"
                ds.SeriesDate = STUDY_DATE
                ds.SeriesTime = "091500.000000"
                ds.AcquisitionNumber = 1
                ds.InstanceNumber = instance
                ds.SOPInstanceUID = uid("qsm", part, e, k)
                ds.ImageType = image_type

                ds.ScanningSequence = "GR"
                ds.SequenceVariant = "SP"
                ds.ScanOptions = ""
                ds.MRAcquisitionType = "3D"
                ds.SequenceName = f"*fl3d{len(echo_times)}"
                ds.AngioFlag = "N"
                ds.RepetitionTime = 40
                ds.EchoTime = te
                ds.EchoNumbers = e + 1
                ds.EchoTrainLength = len(echo_times)
                ds.FlipAngle = 15
                ds.NumberOfAverages = 1
                ds.PixelBandwidth = 300
                ds.PercentSampling = 100
                ds.PercentPhaseFieldOfView = 100
                ds.AcquisitionMatrix = [0, 96, 96, 0]
                ds.InPlanePhaseEncodingDirection = "ROW"
                ds.SliceThickness = spacing
                ds.SpacingBetweenSlices = spacing
                ds.PixelSpacing = [spacing, spacing]
                ds.SAR = 0.02
                axial_geometry(ds, rows, cols, spacing, k)

                img = phantom(rows, cols, nslices, k)
                mask = img > 0
                if part == "mag":
                    t2star = np.where(img > 0.9, 20.0, 50.0)  # iron-rich nuclei decay faster
                    pixels = np.round(img * 3000 * np.exp(-te / t2star))
                else:
                    # Smooth background field plus a local shift in the nuclei,
                    # wrapped to [-pi, pi) and stored Siemens-style in 0..4095.
                    y, x = np.mgrid[-1:1:rows * 1j, -1:1:cols * 1j]
                    field_hz = 8 * x + 5 * y ** 2 + np.where(img > 0.9, 3.0, 0.0)
                    phase = np.angle(np.exp(2j * np.pi * field_hz * te / 1000))
                    pixels = np.where(mask, np.round((phase + np.pi) / (2 * np.pi) * 4095), 2048)
                    ds.RescaleIntercept = -4096
                    ds.RescaleSlope = 2
                    ds.RescaleType = "US"
                pixel_attributes(ds, np.clip(pixels, 0, 4095))
                tag = "M" if part == "mag" else "P"
                files[f"QSM_ME_GRE/{tag}/IM-{series_number:04d}-{instance:04d}.dcm"] = finish(ds)
    return files


def main() -> None:
    files = {"README.txt": README.encode()}
    files.update(t1w_mprage())
    files.update(qsm_multi_echo_gre())

    OUTPUT_ZIP.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(OUTPUT_ZIP, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for name in sorted(files):
            info = zipfile.ZipInfo(f"{SESSION_DIR}/{name}", date_time=ZIP_TIMESTAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, files[name])

    raw = sum(len(v) for v in files.values())
    print(f"Wrote {OUTPUT_ZIP}: {len(files) - 1} DICOMs, "
          f"{raw / 1e6:.2f} MB raw, {OUTPUT_ZIP.stat().st_size / 1e6:.2f} MB zipped")


if __name__ == "__main__":
    main()
