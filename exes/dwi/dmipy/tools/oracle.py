"""Generate discrete sampling tables and forward/optimizer fixtures from pinned dmipy.

Run with numpy1.26.4, scipy1.11.4 and dipy1.7.0:
  python oracle.py PINNED_DMIPY_SOURCE DEST
No AMICO or generic NODDI implementation supplies the expected values.
"""
import hashlib
import json
from pathlib import Path
import sys
import subprocess
import warnings

source, destination = map(Path, sys.argv[1:])
manifest = json.loads(Path(__file__).resolve().parents[1].joinpath("source.manifest.json").read_text())
for entry in manifest["files"]:
    assert hashlib.sha256((source / entry["path"]).read_bytes()).hexdigest() == entry["sha256"], entry["path"]
sys.path.insert(0, str(source))
warnings.filterwarnings("ignore")
import numpy as np
import scipy
import dipy
from dmipy.core.acquisition_scheme import acquisition_scheme_from_bvalues
from dmipy.core.modeling_framework import MultiCompartmentModel
from dmipy.distributions.distribute_models import SD1WatsonDistributed
from dmipy.distributions import distributions
from dmipy.signal_models import cylinder_models, gaussian_models
from dmipy.optimizers.brute2fine import GlobalBruteOptimizer, Brute2FineOptimizer

assert (np.__version__, scipy.__version__, dipy.__version__) == ("1.26.4", "1.11.4", "1.7.0")
destination.mkdir(parents=True, exist_ok=True)
bundle = SD1WatsonDistributed([cylinder_models.C1Stick(), gaussian_models.G2Zeppelin()])
bundle.set_tortuous_parameter("G2Zeppelin_1_lambda_perp", "C1Stick_1_lambda_par", "partial_volume_0")
bundle.set_equal_parameter("G2Zeppelin_1_lambda_par", "C1Stick_1_lambda_par")
bundle.set_fixed_parameter("G2Zeppelin_1_lambda_par", 1.7e-9)
model = MultiCompartmentModel([gaussian_models.G1Ball(), bundle])
model.set_fixed_parameter("G1Ball_1_lambda_iso", 3e-9)
model.volume_fractions_fixed = False
sphere30 = np.loadtxt(source / "dmipy/data/spheres/01-shells-30.txt", skiprows=1)[:, 1:]
vertices = distributions.hemisphere.vertices
sampling = ["// Generated by tools/oracle.py from dmipy2d607321 and DIPY1.7.0.",
            "// SPDX-License-Identifier: MIT AND BSD-3-Clause"]
for name, values in [("HEMISPHERE", vertices), ("START_DIRECTIONS", sphere30)]:
    sampling.append(f"pub const {name}: [[f64; 3]; {len(values)}] = [")
    sampling += ["    [" + ", ".join(repr(float(v)) for v in row) + "]," for row in values]
    sampling.append("];")
(destination / "sampling.rs").write_text("\n".join(sampling) + "\n")
rustfmt = subprocess.check_output(["rustup", "which", "rustfmt"], text=True).strip()
subprocess.run([rustfmt, "--edition", "2024", str(destination / "sampling.rs")], check=True)

bvals = np.r_[0., np.repeat([500., 1000., 2000.], [6, 8, 10])]
gradients = np.vstack(([0., 0., 0.], sphere30[:len(bvals) - 1]))
gradients[1:] /= np.linalg.norm(gradients[1:], axis=1)[:, None]
scheme = acquisition_scheme_from_bvalues(bvals * 1e6, gradients, b0_threshold=50e6)
brute = GlobalBruteOptimizer(model, scheme)
fine = Brute2FineOptimizer(model, scheme)
parameters = [
    [0.2, -1.3, 0.02, 0.99, 0.01], [1.4, 2.2, 0.99, 0.01, 0.99],
    [0.7, -0.4, 0.35, 0.6, 0.1], [2.7, 1.4, 0.7, 0.25, 0.3],
]
for odi in [0.80606061, 0.46666667, 0.25333333, 0.15636364, 0.09818182, 0.06909091]:
    parameters += [[0.6, -2., odi + delta, 0.4, 0.2] for delta in [-1e-9, 1e-9]]
cases = []
for index, vector in enumerate(parameters):
    full = np.r_[vector, 1 - vector[-1]]
    prediction = model(scheme, **model.parameter_vector_to_parameters(full))
    # A deterministic perturbation exercises a real nonzero-residual nonlinear fit.
    measured = prediction + 0.004 * np.sin(np.arange(len(prediction)) * 1.3 + index)
    measured[0] = 1.
    start = brute(measured)
    fitted = fine(measured, start)
    cases.append({"parameters": vector, "prediction": prediction.tolist(), "measured": measured.tolist(),
                  "start": start.tolist(), "fitted": fitted.tolist(), "objective": float(fine.obj_func(fitted[:-1], measured))})
fixture = {"sourceCommit": "2d6073218eb4ebc97645ac6e275270c36834e33d",
           "versions": {"numpy": np.__version__, "scipy": scipy.__version__, "dipy": dipy.__version__},
           "bvals": bvals.tolist(), "gradients": gradients.tolist(), "cases": cases,
           "grid": brute.parameter_grid.tolist()}
(destination / "oracle.json").write_text(json.dumps(fixture, separators=(",", ":")) + "\n")
print(f"{len(cases)} independent forward/fit cases, {len(brute.parameter_grid)} starts")
